#!/usr/bin/env python3
"""Сборка карусели «Садись и выдохни» v3: кроп генераций 3:4 до мастер-формата 1080×1350.

Типографика в v3 НЕ накладывается кодом — она вплавлена в генерацию (openai/gpt-5.4-image-2).
Скрипт только режет 3:4 до 4:5 и собирает контактный лист. Денег не тратит.

Модель отдаёт 3:4 (0,75), мастер SMM — 4:5 (0,8), поэтому по высоте нужно снять ~6,25 %.
Сколько снять сверху и снизу — задано вручную по каждому кадру: срез не должен задеть
ни заголовок, ни подпись. Значения получены измерением полей, см. МАНИФЕСТ.

Запуск: python3 сборка.py
"""
from __future__ import annotations

import pathlib

from PIL import Image

W, H = 1080, 1350  # мастер SMM 4:5 из БАННЕРЫ/formats.yaml
ЗДЕСЬ = pathlib.Path(__file__).resolve().parent

# файл-источник -> (сколько строк снять сверху, сколько снизу, имя финала)
КАДРЫ = [
    ("сырьё/01_c.png", 156, 0, "01_sadis-i-vydohni.png"),
    ("сырьё/03_b.png", 95, 33, "03_svoy-svet-svoya-muzyka.png"),
    ("сырьё/04_b.png", 156, 0, "04_smotret-v-okno.png"),
    ("сырьё/05_c.png", 117, 39, "05_prokatis-kogda-zahochesh.png"),
]


def кроп(путь: pathlib.Path, сверху: int, снизу: int) -> Image.Image:
    im = Image.open(путь).convert("RGB")
    ш, в = im.size
    нужно = в - int(round(ш * H / W))
    if сверху + снизу != нужно:
        raise SystemExit(
            f"{путь.name}: снять надо {нужно} строк, а задано {сверху}+{снизу}={сверху + снизу}"
        )
    im = im.crop((0, сверху, ш, в - снизу))
    return im.resize((W, H), Image.Resampling.LANCZOS)


def контактный_лист(файлы: list[pathlib.Path]) -> None:
    мини_ш, поле = 340, 16
    мини_в = int(мини_ш * H / W)
    лист = Image.new("RGB", (поле + len(файлы) * (мини_ш + поле), мини_в + 2 * поле), (18, 18, 18))
    for i, f in enumerate(файлы):
        м = Image.open(f).resize((мини_ш, мини_в), Image.Resampling.LANCZOS)
        лист.paste(м, (поле + i * (мини_ш + поле), поле))
    лист.save(ЗДЕСЬ / "КОНТАКТНЫЙ-ЛИСТ.png")
    print(f"контактный лист: {лист.size[0]}×{лист.size[1]}")


def main() -> None:
    готовые = []
    for источник, сверху, снизу, имя in КАДРЫ:
        кадр = кроп(ЗДЕСЬ / источник, сверху, снизу)
        путь = ЗДЕСЬ / имя
        кадр.save(путь)
        готовые.append(путь)
        print(f"{имя}  ← {источник}  (срез {сверху} сверху, {снизу} снизу)")
    контактный_лист(готовые)


if __name__ == "__main__":
    main()
