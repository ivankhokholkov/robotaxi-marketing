#!/usr/bin/env python3
"""Сборка карусели «Садись и выдохни» v2: кроп фонов до 1080×1350 и накладка типографики.

Текст в кадр НЕ вплавляется генерацией — кириллица генерацией ломается.
Фон приходит из `фоны/` (Polza AI), типографика кладётся здесь, кодом.

Запуск из папки карусели:
    python3 сборка.py

Ничего не скачивает и денег не тратит: работает только с локальными файлами.
"""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ЗДЕСЬ = Path(__file__).resolve().parent
ФОНЫ = ЗДЕСЬ / "фоны"
ШРИФТЫ = ЗДЕСЬ / "шрифты"

W, H = 1080, 1350          # мастер-формат SMM 4:5 из БАННЕРЫ/formats.yaml
ПОЛОСА = 140               # ширина вертикальной полосы облака точек (сплит-скрин, редакция «намёк»)

ТЁПЛЫЙ_БЕЛЫЙ = (242, 237, 228)
ЧЁРНЫЙ = (13, 20, 22)
БИРЮЗА = (53, 214, 196)    # --color-accent из ЛЕНДИНГ/tokens.css
ФОН_ПОЛОСЫ = (6, 16, 15)

# Цвета оклейки автомобиля — один маленький многоугольник на кадр, как микродеталь.
ОКЛЕЙКА = [(232, 51, 42), (255, 212, 0), (166, 224, 0), (30, 155, 75)]

ЗАГ = str(ШРИФТЫ / "YSTextCond-Heavy.ttf")
ПОД = str(ШРИФТЫ / "YSText-Medium-Web.ttf")

# ── Карточки ──────────────────────────────────────────────────────────────────
# поле: «свет» — тёплый белый прямоугольник с чёрным текстом,
#       «тьма» — чёрный прямоугольник с тёплым белым текстом.
# якорь: доля кадра сверху, которую можно срезать при кропе 3:4 → 4:5.
КАРТОЧКИ = [
    dict(n="01", фон="01_zaryadye.png", якорь=0.62, поле="свет",
         строки=["САДИСЬ", "И ВЫДОХНИ"], подпись="РОБОТАКСИ ЯНДЕКСА. ПРИВЕТ!",
         файл="01_sadis-i-vydohni.png"),
    dict(n="02", фон="02_luzhnetskaya.png", якорь=0.45, поле="тьма",
         строки=["ЕДЕМ", "РОВНО"], подпись="БЕЗ РЕЗКИХ МАНЁВРОВ",
         файл="02_edem-rovno.png"),
    dict(n="03", фон="03_salon.png", якорь=0.30, поле="свет",
         строки=["СВОЙ СВЕТ", "СВОЯ МУЗЫКА"], подпись="ТЫ РЕШАЕШЬ, КАК ТЕБЕ ЕХАТЬ",
         файл="03_svoy-svet-svoya-muzyka.png"),
    dict(n="04", фон="04_okno.png", якорь=0.20, поле="тьма",
         строки=["МОЖНО ПРОСТО", "СМОТРЕТЬ В ОКНО"], подпись="ДОРОГА БЕЗ СУЕТЫ",
         файл="04_smotret-v-okno.png"),
    dict(n="05", фон="05_naberezhnaya.png", якорь=0.30, поле="свет",
         строки=["ПРОКАТИСЬ", "КОГДА ЗАХОЧЕШЬ"], подпись="МОСКВА. РОБОТАКСИ ЯНДЕКСА",
         файл="05_prokatis-kogda-zahochesh.png"),
]


def кроп(путь: Path, якорь: float) -> Image.Image:
    """Кадр 3:4 приводится к 4:5: срезается по высоте, якорь задаёт долю среза сверху."""
    im = Image.open(путь).convert("RGB")
    ш, в = im.size
    нужная_в = round(ш * H / W)
    if нужная_в > в:                       # исходник шире нужного — режем по ширине
        нужная_ш = round(в * W / H)
        x = (ш - нужная_ш) // 2
        im = im.crop((x, 0, x + нужная_ш, в))
    else:
        срез = в - нужная_в
        y = round(срез * якорь)
        im = im.crop((0, y, ш, y + нужная_в))
    return im.resize((W, H), Image.Resampling.LANCZOS)


def подобрать(текст: str, ширина: int, файл: str, старт: int) -> ImageFont.FreeTypeFont:
    размер = старт
    проба = ImageDraw.Draw(Image.new("RGB", (1, 1)))
    while размер > 28:
        шрифт = ImageFont.truetype(файл, размер)
        if проба.textlength(текст, font=шрифт) <= ширина:
            return шрифт
        размер -= 2
    return ImageFont.truetype(файл, 28)


def в_разрядку(draw, xy, текст, шрифт, цвет, трекинг):
    x, y = xy
    for знак in текст:
        draw.text((x, y), знак, font=шрифт, fill=цвет)
        x += draw.textlength(знак, font=шрифт) + трекинг
    return x


def полоса_точек(кадр: Image.Image) -> Image.Image:
    """Фирменный приём кампании в редакции «намёк»: вертикальная грань, справа —
    тот же кадр облаком точек. Без кнопок, шкал, подписей и цифр: это
    представление сцены, а не интерфейс."""
    x0 = W - ПОЛОСА
    сцена = кадр.crop((x0, 0, W, H)).convert("L")
    слой = Image.new("RGBA", (ПОЛОСА, H), ФОН_ПОЛОСЫ + (255,))
    d = ImageDraw.Draw(слой)
    шаг = 10
    for y in range(шаг // 2, H, шаг):
        for x in range(шаг // 2, ПОЛОСА, шаг):
            яркость = сцена.getpixel((x, y)) / 255
            if яркость < 0.06:
                continue
            r = 1.1 + 2.9 * яркость
            a = int(80 + 175 * яркость)
            d.ellipse((x - r, y - r, x + r, y + r), fill=БИРЮЗА + (a,))
    кадр.paste(Image.alpha_composite(кадр.crop((x0, 0, W, H)).convert("RGBA"), слой).convert("RGB"), (x0, 0))
    гр = ImageDraw.Draw(кадр, "RGBA")
    гр.rectangle((x0 - 2, 0, x0, H), fill=БИРЮЗА + (150,))
    return кадр


def карточка(с: dict) -> Image.Image:
    кадр = кроп(ФОНЫ / с["фон"], с["якорь"]).convert("RGB")
    кадр = полоса_точек(кадр)

    свет = с["поле"] == "свет"
    цвет_поля = ТЁПЛЫЙ_БЕЛЫЙ if свет else ЧЁРНЫЙ
    цвет_текста = ЧЁРНЫЙ if свет else ТЁПЛЫЙ_БЕЛЫЙ

    поля_x = 74
    доступно = W - ПОЛОСА - поля_x - 46
    кегль = min(подобрать(t, доступно, ЗАГ, 168).size for t in с["строки"])
    шрифты = [ImageFont.truetype(ЗАГ, кегль) for _ in с["строки"]]
    интерлиньяж = round(кегль * 1.02)
    верх = 58
    низ_текста = верх + интерлиньяж * (len(с["строки"]) - 1) + round(кегль * 1.18)
    низ = низ_текста + 74            # черта плюс воздух
    скос = 54

    слой = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    od = ImageDraw.Draw(слой)
    # Поле под заголовок ростом по тексту. Нижняя грань уходит диагональю —
    # один типографический приём на кадр.
    od.polygon([(0, 0), (W - ПОЛОСА, 0), (W - ПОЛОСА, низ - скос), (0, низ)],
               fill=цвет_поля + (247,))
    кадр = Image.alpha_composite(кадр.convert("RGBA"), слой)

    d = ImageDraw.Draw(кадр)
    y = верх
    for текст, шрифт in zip(с["строки"], шрифты):
        d.text((поля_x, y), текст, font=шрифт, fill=цвет_текста + (255,))
        y += интерлиньяж

    # Бирюзовая черта — единственный акцент в типографике.
    ширина_последней = d.textlength(с["строки"][-1], font=шрифты[-1])
    черта_y = низ_текста + 16
    d.rectangle((поля_x, черта_y, поля_x + min(ширина_последней, доступно) * 0.40, черта_y + 8),
                fill=БИРЮЗА + (255,))

    # Подпись внизу: тёплый белый по фотографии. Вместо плашки — мягкий градиент,
    # чтобы не гасить нижнюю треть кадра с автомобилем.
    выс = 250
    град = Image.new("RGBA", (W - ПОЛОСА, выс), (0, 0, 0, 0))
    гд = ImageDraw.Draw(град)
    for i in range(выс):
        гд.line((0, i, W - ПОЛОСА, i), fill=(6, 16, 15, int(180 * (i / выс) ** 1.7)))
    кадр = кадр.convert("RGBA")
    кадр.alpha_composite(град, (0, H - выс))

    d = ImageDraw.Draw(кадр)
    п_шрифт = ImageFont.truetype(ПОД, 31)
    d.rectangle((поля_x, H - 176, поля_x + 108, H - 172), fill=БИРЮЗА + (255,))
    в_разрядку(d, (поля_x, H - 140), с["подпись"], п_шрифт, ТЁПЛЫЙ_БЕЛЫЙ + (255,), 5)

    # Один многоугольник из оклейки — микродеталь, не вторая декоративная система.
    цвет = ОКЛЕЙКА[int(с["n"]) % len(ОКЛЕЙКА)]
    px, py, s = W - ПОЛОСА - 92, H - 168, 34
    d.polygon([(px, py), (px + s, py - 10), (px + s + 8, py + s - 6), (px + 10, py + s)],
              fill=цвет + (255,))

    return кадр.convert("RGB")


def контактный_лист(файлы: list[Path]) -> None:
    мини_ш, отступ = 340, 22
    мини_в = round(мини_ш * H / W)
    лист = Image.new("RGB", (отступ + (мини_ш + отступ) * len(файлы), мини_в + отступ * 2), (18, 22, 24))
    for i, f in enumerate(файлы):
        м = Image.open(f).resize((мини_ш, мини_в), Image.Resampling.LANCZOS)
        лист.paste(м, (отступ + i * (мини_ш + отступ), отступ))
    лист.save(ЗДЕСЬ / "КОНТАКТНЫЙ-ЛИСТ.png")
    print(f"контактный лист: {лист.size[0]}×{лист.size[1]}")


def main() -> None:
    готовые = []
    for с in КАРТОЧКИ:
        путь = ЗДЕСЬ / с["файл"]
        карточка(с).save(путь)
        готовые.append(путь)
        print(f"{с['n']}: {путь.name}  {Image.open(путь).size}")
    контактный_лист(готовые)


if __name__ == "__main__":
    main()
