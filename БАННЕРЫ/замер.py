#!/usr/bin/env python3
"""Технический замер рекламного макета по требованиям площадок.

Считает то, что не требует суждения: холст, вес, формат, попадание содержимого
в охранную зону, свободные поля под пометку «Реклама», долю площади под текстом,
кегль заголовка. Не оценивает композицию и не заменяет глаза.

Требования берутся из карточек контура фактов и продублированы здесь константами
со ссылкой на карточку. Дата снимка требований: 2026-07-31.

Запуск:
    python3 БАННЕРЫ/замер.py путь/к/макету.png [ещё файлы...]
    python3 БАННЕРЫ/замер.py макет.png --отладка   # сохранит рядом *_отладка.png

Формат определяется по размеру холста. Незнакомый размер — замерит только
общие параметры файла.
"""
from __future__ import annotations

import os
import sys

import numpy as np
from PIL import Image

# Порог «поле чистое»: разброс яркости p99−p1 в поле. Подобран по тёмным макетам
# кампании, где фон почти однороден. Для светлых макетов порог поднимается.
ПОРОГ_РАЗБРОСА = 25
# Порог «резкий контур»: модуль градиента яркости. Отделяет типографику и края
# объектов от плавного фотографического фона и размытия.
ПОРОГ_ГРАДИЕНТА = 24
# Доля пикселей с резким контуром, выше которой поле считается занятым.
ПОРОГ_ДОЛИ_КОНТУРОВ = 0.010
# Доля пикселей, отличающихся от фонового цвета полосы, выше которой поле занято.
ПОРОГ_ДОЛИ_НЕФОНА = 0.005

СПЕЦЫ = {
    (1080, 450): dict(
        имя="UrbanAds, горизонтальный баннер",
        карточка="urbanads-bezopasnaya-zona-1080x450",
        охранная_зона=(990, 410),
        макс_вес_кб=2048,
        форматы=("PNG", "JPEG"),
        мин_кегль={"заголовок": 80, "подзаголовок": 40},
        область_заголовка=(30, 40, 500, 245),
        заметка="Значок «Реклама» 57×14 (десктоп) и 45×10 (мобильные) кладётся "
                "площадкой поверх и не должен перекрывать текст и логотипы.",
    ),
    (1280, 256): dict(
        имя="Яндекс Карты, премиум-баннер",
        карточка="yandex-karty-premium-banner-1280x256",
        свободные_поля_px=60,
        макс_вес_кб=1024,
        форматы=("PNG",),
        мин_кегль={"шрифт": 48},
        область_заголовка=(50, 75, 640, 155),
        заметка="Обводка запрещена, светлый фон не рекомендован (ночной режим "
                "Навигатора). Пометка «Реклама» добавляется автоматически.",
    ),
    (300, 600): dict(
        имя="РСЯ, графический баннер",
        карточка="rsya-razmery-graficheskih-bannerov",
        макс_вес_кб=512,
        форматы=("PNG", "JPEG", "GIF"),
        макс_доля_текста=0.20,
        заметка="Лимит доли текста, логотипов и водяных знаков — 20% площади.",
    ),
}


def яркость(im: Image.Image) -> np.ndarray:
    return np.asarray(im.convert("L"), dtype=np.float32)


def карта_градиента(L: np.ndarray) -> np.ndarray:
    dx = np.abs(np.diff(L, axis=1))[:-1, :]
    dy = np.abs(np.diff(L, axis=0))[:, :-1]
    return dx + dy


def метрики_полосы(L: np.ndarray, G: np.ndarray, box) -> dict:
    x0, y0, x1, y1 = box
    кусок = L[y0:y1, x0:x1]
    g = G[y0:min(y1, G.shape[0]), x0:min(x1, G.shape[1])]
    if кусок.size == 0:
        return dict(разброс=0.0, средняя=0.0, контуры=0.0, нефон=0.0)
    p1, p99 = np.percentile(кусок, [1, 99])
    фон = float(np.median(кусок))
    return dict(
        разброс=float(p99 - p1),
        средняя=float(кусок.mean()),
        # резкие контуры: типографика и края объектов, но не плавный фон
        контуры=float((g > ПОРОГ_ГРАДИЕНТА).mean()) if g.size else 0.0,
        # нефон: ловит тонкие элементы, которые перцентили не видят —
        # красную линию или мелкую плашку на чёрном поле
        нефон=float((np.abs(кусок - фон) > 40).mean()),
    )


def вердикт(m: dict) -> str:
    занято = m["контуры"] > ПОРОГ_ДОЛИ_КОНТУРОВ or m["нефон"] > ПОРОГ_ДОЛИ_НЕФОНА
    return "занято" if занято else "чисто"


def печать_полос(поля: dict) -> None:
    for имя, m in поля.items():
        print(f"    {имя:9s} разброс {m['разброс']:6.1f}   средняя {m['средняя']:6.1f}   "
              f"контуры {m['контуры']*100:5.2f}%   нефон {m['нефон']*100:5.2f}%   → {вердикт(m)}")


def строки_из_маски(маска: np.ndarray, мин_высота: int = 4) -> list[tuple[int, int, int, int]]:
    """Режет маску на строки по горизонтальной проекции, возвращает рамки строк."""
    строки = маска.any(axis=1)
    рамки, начало = [], None
    for y, есть in enumerate(np.append(строки, False)):
        if есть and начало is None:
            начало = y
        elif not есть and начало is not None:
            if y - начало >= мин_высота:
                столбцы = np.where(маска[начало:y].any(axis=0))[0]
                рамки.append((int(столбцы[0]), начало, int(столбцы[-1]) + 1, y))
            начало = None
    return рамки


def замер_охранной_зоны(L, G, w, h, зона) -> dict:
    зw, зh = зона
    sx, sy = (w - зw) // 2, (h - зh) // 2
    поля = {
        "левое": (0, 0, sx, h),
        "правое": (w - sx, 0, w, h),
        "верхнее": (sx, 0, w - sx, sy),
        "нижнее": (sx, h - sy, w - sx, h),
    }
    return {имя: метрики_полосы(L, G, box) for имя, box in поля.items()}, (sx, sy)


def замер_свободных_полей(L, G, w, h, поле_px) -> dict:
    поля = {
        "левое": (0, 0, поле_px, h),
        "правое": (w - поле_px, 0, w, h),
    }
    return {имя: метрики_полосы(L, G, box) for имя, box in поля.items()}


def маска_букв(im: Image.Image) -> np.ndarray:
    """Пиксели типографики.

    Кампания строит заголовок как тёмные буквы на светлой издательской плашке,
    поэтому буквы ищутся только там, где в этой же строке есть плашка: так
    красная кинетическая плоскость и ночная фотография не попадают в текст.
    Если плашки нет, работает обратный случай — светлые буквы на тёмном фоне.
    """
    a = np.asarray(im.convert("RGB"), dtype=np.int16)
    mx, mn = a.max(axis=2), a.min(axis=2)
    насыщенность = mx - mn
    плашка = (mx > 205) & (насыщенность < 40) & (a[..., 0] >= a[..., 2])
    чернила = (mx < 120) & (насыщенность < 60)

    буквы = np.zeros_like(чернила)
    for y in range(буквы.shape[0]):
        xs = np.where(плашка[y])[0]
        if len(xs) >= 25:
            буквы[y, xs.min():xs.max() + 1] = чернила[y, xs.min():xs.max() + 1]
    if буквы.sum() < 200:  # плашки нет — светлое на тёмном
        буквы = (mx > 200) & (насыщенность < 40)
    return буквы


def замер_доли_текста(im: Image.Image, отладка=None) -> dict:
    """Доля площади под текстом.

    Три числа: сумма рамок строк (так лимит площадки обычно и трактуют), общая
    рамка блока и площадь самих букв. Результат проверяется глазами по
    отладочной картинке: рамки строк на ней обведены.
    """
    буквы = маска_букв(im)
    h, w = буквы.shape
    # строка засчитывается, если в ней хотя бы 10% ширины холста под буквами:
    # отсекает тонкие подчёркивания и хвосты соседней строки
    плотные = буквы.copy()
    плотные[буквы.sum(axis=1) < w * 0.10] = False

    строки = строки_из_маски(плотные, мин_высота=6)
    итог = dict(строки=строки, площадь=w * h,
                рамки_строк=sum((c - a) * (d - b) for a, b, c, d in строки),
                пиксели_букв=int(буквы.sum()), общая_рамка=0)
    if строки:
        ux0 = min(s[0] for s in строки); uy0 = min(s[1] for s in строки)
        ux1 = max(s[2] for s in строки); uy1 = max(s[3] for s in строки)
        итог["общая_рамка"] = (ux1 - ux0) * (uy1 - uy0)
    if отладка is not None:
        from PIL import ImageDraw
        слой = im.convert("RGB").copy()
        d = ImageDraw.Draw(слой)
        for s in строки:
            d.rectangle(s, outline=(255, 59, 48), width=2)
        слой.save(отладка)
    return итог


def замер_заголовка(im: Image.Image, область) -> list[tuple[int, int, int, int]]:
    """Рамки строк заголовка: светлые буквы на тёмном фоне, в заданной области."""
    L = яркость(im)
    x0, y0, x1, y1 = область
    маска = L[y0:y1, x0:x1] > 195
    маска[маска.sum(axis=1) < 10] = False
    return [(a + x0, b + y0, c + x0, d + y0)
            for a, b, c, d in строки_из_маски(маска, мин_высота=6)]


def проверить(путь: str, отладка: bool = False) -> None:
    im = Image.open(путь)
    w, h = im.size
    вес_кб = os.path.getsize(путь) / 1024
    L = яркость(im)
    G = карта_градиента(L)
    спец = СПЕЦЫ.get((w, h))

    print(f"\n=== {os.path.basename(путь)} ===")
    print(f"Холст: {w}×{h}   Вес: {вес_кб:.0f} КБ   Формат: {im.format}   Режим: {im.mode}")
    if not спец:
        print("Размер не из матрицы форматов — замерены только общие параметры.")
        return
    print(f"Площадка: {спец['имя']}   Требования: {спец['карточка']}")

    ok = спец["макс_вес_кб"]
    print(f"  вес: {'ок' if вес_кб <= ok else 'ПРЕВЫШЕН'} ({вес_кб:.0f} из {ok} КБ)")
    print(f"  формат: {'ок' if im.format in спец['форматы'] else 'НЕ ПОДХОДИТ'} "
          f"({im.format}, допустимы {'/'.join(спец['форматы'])})")

    граница_слева = граница_справа = None
    if "охранная_зона" in спец:
        поля, (sx, sy) = замер_охранной_зоны(L, G, w, h, спец["охранная_зона"])
        зw, зh = спец["охранная_зона"]
        граница_слева, граница_справа = sx, w - sx
        print(f"  охранная зона {зw}×{зh}, поля {sx} px по горизонтали и {sy} px по вертикали:")
        печать_полос(поля)

    if "свободные_поля_px" in спец:
        п = спец["свободные_поля_px"]
        граница_слева, граница_справа = п, w - п
        print(f"  свободная область под пометку «Реклама», от {п} px слева и справа:")
        печать_полос(замер_свободных_полей(L, G, w, h, п))

    if "макс_доля_текста" in спец:
        путь_отл = путь.replace(".png", "_отладка.png") if отладка else None
        t = замер_доли_текста(im, путь_отл)
        S = t["площадь"]
        print(f"  доля текста, лимит {спец['макс_доля_текста']*100:.0f}%:")
        print(f"    сумма рамок строк: {t['рамки_строк']/S*100:5.2f}%  ({len(t['строки'])} строк)")
        print(f"    общая рамка блока: {t['общая_рамка']/S*100:5.2f}%")
        print(f"    пиксели самих букв: {t['пиксели_букв']/S*100:5.2f}%")
        for s in t["строки"]:
            print(f"      строка {s}  высота {s[3]-s[1]} px")
        if путь_отл:
            print(f"    отладка: {путь_отл}")

    if "область_заголовка" in спец:
        рамки = замер_заголовка(im, спец["область_заголовка"])
        требование = ", ".join(f"{k} — {v}" for k, v in спец["мин_кегль"].items())
        print(f"  заголовок, поиск в области {спец['область_заголовка']}, "
              f"минимальный кегль по требованию: {требование}")
        for x0, y0, x1, y1 in рамки:
            высота = y1 - y0
            кегль = round(высота / 0.72)  # заглавная ≈ 0,72 кегля у гротесков
            запас = ""
            if граница_слева is not None:
                запас = (f"   запас слева {x0 - граница_слева:+d} px, "
                         f"справа {граница_справа - x1:+d} px")
            print(f"    строка ({x0}, {y0}, {x1}, {y1})   заглавная {высота} px "
                  f"≈ кегль {кегль}{запас}")
        if not рамки:
            print("    не найдено")

    print(f"  ! {спец['заметка']}")


if __name__ == "__main__":
    аргументы = [a for a in sys.argv[1:] if not a.startswith("--")]
    отладка = "--отладка" in sys.argv
    if not аргументы:
        print(__doc__)
        sys.exit(0)
    for путь in аргументы:
        проверить(путь, отладка)
