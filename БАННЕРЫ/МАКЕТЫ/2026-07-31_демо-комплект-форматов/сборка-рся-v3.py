#!/usr/bin/env python3
"""Сборка РСЯ 300×600 версии v3: чистый фон генерацией + типографика кодом.

Зачем отдельный скрипт. У формата 300×600 в `БАННЕРЫ/formats.yaml` стоит
`путь_текста: накладка_кодом`. У версий 2026-07-31 типографика была вплавлена
в генерацию, поэтому доля площади под текстом (лимит РСЯ — 20%) считалась уже
по готовому файлу и правилась только перегенерацией: 18,54% построчно и 22,20%
по общей рамке блока. Здесь маршрут правильный: генератор отдаёт фон без единой
буквы, а заголовок кладёт код — доля площади считается ДО сборки, а смена
оффера стоит один запуск скрипта, а не новую картинку.

Что делает скрипт:
  1. кропает сгенерированный фон 9:16 до пропорции 1:2 и уменьшает до 300×600
     (генератор не умеет 1:2; кроп и даунскейл дают резкость лучше апскейла);
  2. подбирает кегль заголовка так, чтобы доля площади проходила ОБЕ трактовки
     лимита 20% с запасом, и печатает получившиеся цифры;
  3. строит под получившийся блок тёпло-белое издательское поле — повёрнутый
     прямоугольник, как в макете 31.07, и кладёт его через маску 4×, чтобы
     наклонная грань не давала лесенку;
  4. печатает строки, сжатые по горизонтали до пропорций исходного макета;
  5. сохраняет PNG и проверяет вес против лимита 512 КБ.

Смена оффера: поменять ЗАГОЛОВОК ниже и запустить снова. Кегль подберётся сам,
фон не перегенерируется. Тексты перед этим прогоняются через `brand-check`.

Запуск: python3 БАННЕРЫ/МАКЕТЫ/2026-07-31_демо-комплект-форматов/сборка-рся-v3.py
"""
from __future__ import annotations

import math
import os

from PIL import Image, ImageDraw, ImageFont

ПАПКА = os.path.dirname(os.path.abspath(__file__))
ФОН = os.path.join(ПАПКА, "raw-v3", "фон-06.png")
ВЫХОД = os.path.join(ПАПКА, "final", "05_rsya-300x600-v3.png")

ХОЛСТ = (300, 600)
ЛИМИТ_ВЕСА_КБ = 512

# Кроп исходника 1520×2688 (9:16) до 1:2. Окно выбрано глазами: машина целиком,
# чёрное поле сверху, красная диагональ входит справа.
КРОП = (160, 0, 160 + 1200, 2400)

# --- текст -------------------------------------------------------------------
# Формулировки сверены со `references/стоп-слова.md` и `references/rtb-факты.md`.
# Кампания «Москва видит больше», сегмент — обе аудитории, стадия знание–интерес,
# оффера нет. Цифр, обещаний и сравнений с такси с водителем в строках нет.
ЗАГОЛОВОК = ["МОСКВА", "ВИДИТ", "БОЛЬШЕ"]

# Гротеска, которой нарисован макет 31.07, файлом в системе нет: генератор
# нарисовал сжатый (compressed) гротеск, а самый узкий реальный кириллический
# чёрный в системе — Sofia Sans Extra Condensed Black (SIL OFL). Он шире
# нарисованного примерно на треть, поэтому строка дополнительно сжимается по
# горизонтали до пропорции исходного макета. Сжатие делается по маске в 4×
# передискретизации, поэтому края остаются чистыми.
ШРИФТ = "/Library/Fonts/SofiaSansExtraCondensed-Black.ttf"
СЖАТИЕ = 0.72          # горизонтальный масштаб строки
СУПЕРСЭМПЛ = 4         # во сколько раз рендерим текст перед уменьшением

# --- геометрия ---------------------------------------------------------------
# Тёпло-белое издательское поле строится не руками, а от текстового блока:
# минимальный повёрнутый прямоугольник, который накрывает блок с запасом.
# Поменяется заголовок — поле пересоберётся само.
ПОЛЕ_УГОЛ = -6.0                # наклон, верхняя грань поднимается вправо
ПОЛЕ_ЗАПАС = 14                 # поля вокруг текста, px
ПОЛЕ_ЦВЕТ = (243, 240, 234)     # тёплый белый издательского поля
ЧЕРНИЛА = (18, 18, 18)

# Нижняя граница поля. Ниже неё на фоне начинаются подсвеченные тёплые окна.
# Если тёпло-белое поле уходит ниже, между его диагональной гранью и этими
# окнами остаётся тёмная полоса фасада, и эвристика `БАННЕРЫ/замер.py` считает
# её четвёртой строкой текста: общая рамка блока прыгает с 17% до 19,5%.
# Константа привязана к конкретному фону — при смене фона перепроверить замером.
ПОЛЕ_НИЗ = 262

# Текстовый блок: левый край задан, верх считается от нижней границы поля.
БЛОК_X = 28
ИНТЕРЛИНЬЯЖ = 10                # просвет между строками, px:
                                # у «Д» есть выносные элементы, при 5 px
                                # они садятся на заглавные следующей строки
МАКС_ШИРИНА_БЛОКА = 176         # чтобы блок не выходил за правую грань поля

# Цели по доле площади. Лимит площадки — 20% при обеих трактовках; берём запас.
ЦЕЛЬ_СТРОКИ = 0.160             # сумма рамок строк
ЦЕЛЬ_БЛОК = 0.180               # общая рамка блока

# Красный кинетический жест на макете один и он уже есть на фоне: полоса входит
# из правого верхнего угла и уходит ЗА тёпло-белое поле. Поверх поля она не
# дорисовывается сознательно — второй красный элемент дал бы две конкурирующие
# декоративные системы, что визуальная система прямо запрещает.


def повёрнутый_прямоугольник(центр, размер, угол_град):
    cx, cy = центр
    w, h = размер
    a = math.radians(угол_град)
    cos, sin = math.cos(a), math.sin(a)
    точки = []
    for dx, dy in ((-w / 2, -h / 2), (w / 2, -h / 2), (w / 2, h / 2), (-w / 2, h / 2)):
        точки.append((cx + dx * cos - dy * sin, cy + dx * sin + dy * cos))
    return точки


def маска_строки(текст: str, кегль_cap: int) -> Image.Image:
    """Маска строки с нужной высотой заглавной и горизонтальным сжатием."""
    проба = ImageFont.truetype(ШРИФТ, 400)
    cap_400 = проба.getbbox("М")[3] - проба.getbbox("М")[1]
    размер = max(8, round(400 * кегль_cap * СУПЕРСЭМПЛ / cap_400))
    f = ImageFont.truetype(ШРИФТ, размер)
    bb = f.getbbox(текст)
    m = Image.new("L", (bb[2] - bb[0] + 4, bb[3] - bb[1] + 4), 0)
    ImageDraw.Draw(m).text((2 - bb[0], 2 - bb[1]), текст, font=f, fill=255)
    m = m.crop(m.getbbox())
    новая = (max(1, round(m.width * СЖАТИЕ / СУПЕРСЭМПЛ)),
             max(1, round(m.height / СУПЕРСЭМПЛ)))
    return m.resize(новая, Image.Resampling.LANCZOS)


def поле_под_блок(блок):
    """Повёрнутый прямоугольник, накрывающий блок с запасом ПОЛЕ_ЗАПАС."""
    x0, y0, x1, y1 = блок
    w, h = x1 - x0, y1 - y0
    a = math.radians(ПОЛЕ_УГОЛ)
    cos, sin = abs(math.cos(a)), abs(math.sin(a))
    размер = (w * cos + h * sin + 2 * ПОЛЕ_ЗАПАС, w * sin + h * cos + 2 * ПОЛЕ_ЗАПАС)
    центр = ((x0 + x1) / 2, (y0 + y1) / 2)
    return повёрнутый_прямоугольник(центр, размер, ПОЛЕ_УГОЛ), размер


def верх_блока(блок_w: int, блок_h: int) -> int:
    """Верх текстового блока, при котором низ поля попадает ровно в ПОЛЕ_НИЗ."""
    a = math.radians(ПОЛЕ_УГОЛ)
    cos, sin = abs(math.cos(a)), abs(math.sin(a))
    полу_w = (блок_w * cos + блок_h * sin) / 2 + ПОЛЕ_ЗАПАС
    полу_h = (блок_w * sin + блок_h * cos) / 2 + ПОЛЕ_ЗАПАС
    вынос = полу_w * sin + полу_h * cos      # от центра поля до его нижней точки
    return round(ПОЛЕ_НИЗ - блок_h / 2 - вынос)


def разложить(строки: list[str], cap: int):
    """Маски строк и их рамки на холсте.

    Шаг между строками считается от высоты заглавной, а не от высоты рамки:
    у кириллической «Д» есть выносные элементы ниже базовой линии, и если
    вести отсчёт по рамке, просветы между строками получаются разными.
    Рамки при этом остаются честными — выносной элемент в них входит, как
    его и увидит замер площадки.
    """
    маски = [маска_строки(s, cap) for s in строки]
    блок_w = max(m.width for m in маски)
    блок_h = (cap + ИНТЕРЛИНЬЯЖ) * (len(маски) - 1) + маски[-1].height
    y = верх_блока(блок_w, блок_h)
    рамки = []
    for m in маски:
        рамки.append((БЛОК_X, y, БЛОК_X + m.width, y + m.height))
        y += cap + ИНТЕРЛИНЬЯЖ
    return маски, рамки


def подобрать_кегль(строки: list[str]) -> tuple[int, list[Image.Image], list, dict]:
    """Наибольшая высота заглавной, при которой обе трактовки лимита проходят."""
    S = ХОЛСТ[0] * ХОЛСТ[1]
    for cap in range(90, 15, -1):
        маски, рамки = разложить(строки, cap)
        сумма = sum((x1 - x0) * (y1 - y0) for x0, y0, x1, y1 in рамки)
        блок_w = max(x1 for _, _, x1, _ in рамки) - min(x0 for x0, _, _, _ in рамки)
        блок_h = max(y1 for _, _, _, y1 in рамки) - min(y0 for _, y0, _, _ in рамки)
        if блок_w > МАКС_ШИРИНА_БЛОКА:
            continue
        if сумма / S <= ЦЕЛЬ_СТРОКИ and блок_w * блок_h / S <= ЦЕЛЬ_БЛОК:
            цифры = dict(cap=cap, ширины=[m.width for m in маски],
                         высоты=[m.height for m in маски],
                         сумма=сумма, доля_строк=сумма / S,
                         блок=(блок_w, блок_h), доля_блока=блок_w * блок_h / S)
            return cap, маски, рамки, цифры
    raise SystemExit("Не удалось подобрать кегль: заголовок слишком длинный для 300×600")


def собрать() -> None:
    исходник = Image.open(ФОН).convert("RGB")
    фон = исходник.crop(КРОП).resize(ХОЛСТ, Image.Resampling.LANCZOS)

    cap, маски, рамки, ц = подобрать_кегль(ЗАГОЛОВОК)
    блок = (min(r[0] for r in рамки), min(r[1] for r in рамки),
            max(r[2] for r in рамки), max(r[3] for r in рамки))
    углы, размер_поля = поле_под_блок(блок)

    # Поле кладётся через маску в 4× передискретизации: наклонная грань,
    # залитая напрямую, даёт лесенку, заметную уже в реальном размере показа.
    маска_поля = Image.new("L", (ХОЛСТ[0] * СУПЕРСЭМПЛ, ХОЛСТ[1] * СУПЕРСЭМПЛ), 0)
    ImageDraw.Draw(маска_поля).polygon(
        [(x * СУПЕРСЭМПЛ, y * СУПЕРСЭМПЛ) for x, y in углы], fill=255)
    маска_поля = маска_поля.resize(ХОЛСТ, Image.Resampling.LANCZOS)

    слой = фон.copy()
    слой.paste(Image.new("RGB", ХОЛСТ, ПОЛЕ_ЦВЕТ), (0, 0), маска_поля)
    for m, (x0, y0, _, _) in zip(маски, рамки):
        слой.paste(Image.new("RGB", m.size, ЧЕРНИЛА), (x0, y0), m)

    os.makedirs(os.path.dirname(ВЫХОД), exist_ok=True)
    слой.save(ВЫХОД, optimize=True)
    вес = os.path.getsize(ВЫХОД) / 1024

    S = ХОЛСТ[0] * ХОЛСТ[1]
    print(f"{os.path.basename(ВЫХОД)}: {ХОЛСТ[0]}×{ХОЛСТ[1]}, {вес:.0f} КБ "
          f"(лимит {ЛИМИТ_ВЕСА_КБ} КБ) — {'ок' if вес <= ЛИМИТ_ВЕСА_КБ else 'ПРЕВЫШЕН'}")
    print(f"  шрифт: {os.path.basename(ШРИФТ)}, сжатие {СЖАТИЕ}, "
          f"заглавная {cap} px ≈ кегль {round(cap / 0.72)} px")
    print(f"  строки: " + ", ".join(f"{t} {w}×{h}" for t, w, h
                                    in zip(ЗАГОЛОВОК, ц['ширины'], ц['высоты'])))
    print(f"  блок {ц['блок'][0]}×{ц['блок'][1]} px, рамки {рамки}")
    print(f"  тёпло-белое поле {размер_поля[0]:.0f}×{размер_поля[1]:.0f} px, "
          f"наклон {ПОЛЕ_УГОЛ}°, нижняя точка y={max(y for _, y in углы):.0f} "
          f"(предел {ПОЛЕ_НИЗ})")
    print(f"  доля текста: сумма рамок строк {ц['доля_строк']*100:.2f}%, "
          f"общая рамка блока {ц['доля_блока']*100:.2f}%  (лимит 20%)")
    print(f"  контроль: python3 БАННЕРЫ/замер.py {ВЫХОД} --отладка")


if __name__ == "__main__":
    собрать()
