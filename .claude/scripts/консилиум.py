class Оборвалось(Exception):
    """Прогон не дошёл до конца. То, что успело отработать, всё равно пишется на диск."""


def ключи() -> list[tuple[str, str]]:
    """Все источники ключа по порядку, а не первый попавшийся.

    Протухший ключ в ~/.zshrc перекрывает рабочий из .env, и запрос падает с 401
    там, где ключ вообще-то есть. Поэтому источники перебираются, а не выбирается
    один: см. ПАМЯТЬ/ГРАБЛИ.md.
    """
    найдено: list[tuple[str, str]] = []
    if os.environ.get("POLZA_AI_API_KEY"):
        найдено.append(("переменная окружения", os.environ["POLZA_AI_API_KEY"]))
    for env in (КОРЕНЬ / ".env", КОРЕНЬ.parent / ".env", КОРЕНЬ.parent.parent / ".env"):
        if env.is_file():
            for line in env.read_text().splitlines():
                if line.startswith("POLZA_AI_API_KEY="):
                    найдено.append((str(env), line.split("=", 1)[1].strip()))
    if not найдено:
        sys.exit("Нет ключа POLZA_AI_API_KEY: задайте переменную окружения "
                 "или положите .env рядом с папкой проекта (в сам проект ключ не кладём).")
    return найдено


РАБОЧИЙ_КЛЮЧ: list[tuple[str, str]] = []


def спросить(модель: str, системный: str, запрос: str, лимит: int) -> tuple[str, float]:
    тело = json.dumps({
        "model": модель,
        "messages": [{"role": "system", "content": системный},
                     {"role": "user", "content": запрос}],
        "max_tokens": лимит,
    }, ensure_ascii=False).encode()

    источники = РАБОЧИЙ_КЛЮЧ or ключи()
    последняя = ""
    for откуда, ключ in источники:
        req = urllib.request.Request(API, data=тело, headers={
            "Authorization": f"Bearer {ключ}",
            "Content-Type": "application/json",
        })
        try:
            with urllib.request.urlopen(req, timeout=600) as r:
                ответ = json.load(r)
        except urllib.error.HTTPError as e:
            последняя = f"{e.code}: {e.read().decode()[:300]}"
            if e.code in (401, 403) and len(источники) > 1:
                print(f"ключ из «{откуда}» не принят ({e.code}), пробую следующий",
                      file=sys.stderr)
                continue
            raise Оборвалось(f"модель {модель}, ключ из «{откуда}» — {последняя}")
        if not РАБОЧИЙ_КЛЮЧ:
            РАБОЧИЙ_КЛЮЧ.append((откуда, ключ))
            print(f"ключ взят из «{откуда}»", file=sys.stderr)
        break
    else:
        sys.exit(f"Ни один из {len(источники)} найденных ключей не принят. "
                 f"Последняя ошибка — {последняя}")

    выбор = ответ["choices"][0]
    текст = (выбор["message"].get("content") or "").strip()
    if not текст:
        # Рассуждающая модель могла упереться в лимит до первого видимого токена.
        причина = выбор.get("finish_reason")
        sys.exit(f"Модель {модель} вернула пустой ответ (finish_reason={причина}). "
                 f"Поднимите --лимит-токенов, сейчас {лимит}.")
    return текст, float(ответ.get("usage", {}).get("cost_rub") or 0)


def проверить_nda(текст: str, разрешено: bool) -> None:
    найдено = sorted({m.group(0) for p in МАРКЕРЫ_NDA
                      for m in re.finditer(p, текст, re.IGNORECASE)})
    if not найдено:
        return
    if разрешено:
        print(f"Внимание: в тексте есть {', '.join(найдено)} — "
              f"вы подтвердили обезличивание флагом --обезличено.", file=sys.stderr)
        return
    sys.exit("В материале найдены закрытые сущности: " + ", ".join(найдено) +
             ".\nМатериал уходит во внешние модели, которые не хранят данные в РФ.\n"
             "Обезличьте текст и запустите снова с флагом --обезличено.")


def main() -> None:
    ap = argparse.ArgumentParser(description="Консилиум на трёх разных моделях через Polza")
    ap.add_argument("--материал", required=True, action="append",
                    help="файл материала (можно несколько раз)")
    ap.add_argument("--тезисы", required=True,
                    help="файл со списком проверяемых утверждений, по одному на строку")
    ap.add_argument("--выход", required=True, help="куда записать разбор")
    ap.add_argument("--прокурор", default=МОДЕЛИ["прокурор"])
    ap.add_argument("--защитник", default=МОДЕЛИ["защитник"])
    ap.add_argument("--судья", default=МОДЕЛИ["судья"])
    ap.add_argument("--лимит-токенов", type=int, default=6000, dest="лимит")
    ap.add_argument("--обезличено", action="store_true",
                    help="подтверждаю: закрытые данные из материала убраны")
    a = ap.parse_args()

    материал = "\n\n".join(
        f"### Файл {p}\n\n{pathlib.Path(p).read_text(encoding='utf-8')}"
        for p in a.материал)
    тезисы = pathlib.Path(a.тезисы).read_text(encoding="utf-8").strip()
    проверить_nda(материал + "\n" + тезисы, a.обезличено)

    основа = f"# Материал\n\n{материал}\n\n# Проверяемые тезисы\n\n{тезисы}"
    расход: list[tuple[str, str, float]] = []
    атака = защита = вердикт = ""
    обрыв = ""

    try:
        print(f"прокурор  → {a.прокурор}", file=sys.stderr)
        атака, ц1 = спросить(a.прокурор, ОБЩЕЕ + "\n\n" + РОЛИ["прокурор"], основа, a.лимит)
        расход.append(("прокурор", a.прокурор, ц1))

        # Защитник НЕ видит атаку. Тот, кто видит, начинает отвечать прокурору
        # вместо своей работы, и позиции перестают быть независимыми.
        print(f"защитник  → {a.защитник}", file=sys.stderr)
        защита, ц2 = спросить(a.защитник, ОБЩЕЕ + "\n\n" + РОЛИ["защитник"], основа, a.лимит)
        расход.append(("защитник", a.защитник, ц2))

        print(f"судья     → {a.судья}", file=sys.stderr)
        вердикт, ц3 = спросить(a.судья, ОБЩЕЕ + "\n\n" + РОЛИ["судья"],
                               f"{основа}\n\n# Атака прокурора\n\n{атака}"
                               f"\n\n# Ответ защитника\n\n{защита}", a.лимит)
        расход.append(("судья", a.судья, ц3))
    except Оборвалось as e:
        обрыв = str(e)
        print(f"прогон оборвался: {обрыв}", file=sys.stderr)

    ПРОПУЩЕНО = ("_Роль не отработала: прогон оборвался раньше. "
                 "Запустите скрипт повторно, когда причина уйдёт._")
    атака = атака or ПРОПУЩЕНО
    защита = защита or ПРОПУЩЕНО
    вердикт = вердикт or ПРОПУЩЕНО
    шапка = ("" if not обрыв else
             f"> ⚠️ **Прогон неполный.** {обрыв}\n>\n"
             f"> Ниже только те роли, которые успели отработать. "
             f"Читать как разбор нельзя: без судьи вердикта нет.\n\n")

    итого = sum(ц for _, _, ц in расход)
    строки = "\n".join(f"| {роль} | `{модель}` | {цена:.2f} |" for роль, модель, цена in расход)
    файлы = ", ".join(f"`{p}`" for p in a.материал)

    документ = f"""# Консилиум: {pathlib.Path(a.материал[0]).stem}

{шапка}Дата {dt.date.today().strftime('%d.%m.%Y')}. Проверяемые материалы: {файлы}.
Три роли шли на трёх разных моделях разных провайдеров — одна модель в трёх
ролях спорит сама с собой и приходит к своему же исходному мнению.

| Роль | Модель | ₽ |
|---|---|---|
{строки}
| **итого** | | **{итого:.2f}** |

---

## Атака прокурора

{атака}

---

## Ответ защитника

{защита}

---

## Решение судьи

{вердикт}

---
Опирается на: {файлы}, [[матрица-сегментов]], [[АКТУАЛИЗАЦИЯ]], [[стоп-слова]]
"""
    out = pathlib.Path(a.выход)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(документ, encoding="utf-8")
    print(f"готово: {out}  ({итого:.2f} ₽)")


if __name__ == "__main__":
    main()
